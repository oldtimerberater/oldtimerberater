	<section id="advisory" aria-labelledby="advisory-title">
		<h2 id="advisory-title">The Advisory</h2>

		<p>The advisory exists for collectors seeking a specific historically significant motor car.</p>

		<p>It begins with the collector’s requirements, not with an available automobile.</p>

		<p>
			No inventory is maintained. No preselected motor car is promoted. The advisory has no interest
			in directing the collector towards an automobile merely because it is available.
		</p>
	</section>

	<section id="historical-significance" aria-labelledby="significance-title">
		<h2 id="significance-title">Historical Significance</h2>

		<p>
			A motor car’s significance can arise from its provenance, rarity, coachwork, originality,
			state of preservation, association with a person or event, or place in motoring history.
		</p>

		<p>Age alone does not establish significance.</p>

		<p>
			The advisory concerns motor cars whose historical identity and collectable importance justify
			serious research and careful judgement.
		</p>
	</section>
